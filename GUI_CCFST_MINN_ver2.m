%% ---------- L/r ----------
uicontrol(pOut,...
    'Style','text',...
    'String','Calculated Slenderness Ratio, L/r',...
    'HorizontalAlignment','left',...
    'FontSize',15,...
    'BackgroundColor','white',...
    'Position',[40 210 320 35]);

txt_Lr = uicontrol(pOut,...
    'Style','edit',...
    'String','---',...
    'FontSize',18,...
    'FontWeight','bold',...
    'BackgroundColor',[0.94 0.94 0.94],...
    'Enable','inactive',...
    'Position',[380 205 140 45]);

%% ---------- Limitation ----------
uicontrol(pOut,...
    'Style','text',...
    'String','Limitation Status',...
    'HorizontalAlignment','left',...
    'FontSize',15,...
    'BackgroundColor','white',...
    'Position',[40 120 220 35]);

txt_limit = uicontrol(pOut,...
    'Style','text',...
    'String','---',...
    'HorizontalAlignment','left',...
    'FontSize',15,...
    'FontWeight','bold',...
    'BackgroundColor','white',...
    'Position',[260 120 380 35]);

%% ============================================================
% BUTTONS
%% ============================================================

btnW = 170;
