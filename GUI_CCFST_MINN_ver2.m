function GUI_CCFST_MINN_ver2
% ============================================================
% GUI for MINN-based CCFST Axial Capacity Prediction
% ============================================================

close all; clc;

%% ============================================================
% LOAD TRAINED MODEL
%% ============================================================

global nets muXs stdXs muys stdys RMSE R2

% Load the five fold files exported by MINN_N_S_5_Fold.m:
% Results_MINN_N_S_5Fold/Fold_XX/MINN_Model_Fold_XX.mat
guiFolder = fileparts(mfilename('fullpath'));
searchFolders = {guiFolder, ...
    fullfile(guiFolder,'Results_MINN_N_S_5Fold'), ...
    pwd, ...
    fullfile(pwd,'Results_MINN_N_S_5Fold')};

% Locate a result folder that contains all five Fold_XX subfolders.
modelFolder = '';
for iFolder = 1:numel(searchFolders)
    candidate = searchFolders{iFolder};
    if isfolder(candidate) && hasFiveFoldFiles(candidate)
        modelFolder = candidate;
        break;
    end
end

% Also search recursively for Fold_01 and infer the result-folder location.
if isempty(modelFolder)
    recursiveRoots = unique({guiFolder,pwd});
    for iRoot = 1:numel(recursiveRoots)
        matches = dir(fullfile(recursiveRoots{iRoot},'**', ...
            'MINN_Model_Fold_01*.mat'));
        for iMatch = 1:numel(matches)
            candidate = fileparts(matches(iMatch).folder);
            if hasFiveFoldFiles(candidate)
                modelFolder = candidate;
                break;
            end
        end
        if ~isempty(modelFolder)
            break;
        end
    end
end

if isempty(modelFolder)
    selectedFolder = uigetdir(guiFolder, ...
        ['Select Results_MINN_N_S_5Fold containing Fold_01 ' ...
         'through Fold_05']);
    if isequal(selectedFolder,0)
        error(['The model folder was not selected. Select the folder ' ...
            'Results_MINN_N_S_5Fold created by MINN_N_S_5_Fold.m.']);
    end
    if ~hasFiveFoldFiles(selectedFolder)
        error(['The selected folder does not contain all five model files ' ...
            'under Fold_01 through Fold_05.']);
    end
    modelFolder = selectedFolder;
end

nFolds = 5;
nets  = cell(nFolds,1);
muXs  = cell(nFolds,1);
stdXs = cell(nFolds,1);
muys  = cell(nFolds,1);
stdys = cell(nFolds,1);

for iFold = 1:nFolds
    foldFolder = fullfile(modelFolder,sprintf('Fold_%02d',iFold));
    matches = dir(fullfile(foldFolder, ...
        sprintf('MINN_Model_Fold_%02d*.mat',iFold)));
    if numel(matches) ~= 1
        error('Expected exactly one model file for Fold %d in %s.', ...
            iFold,foldFolder);
    end
    modelFile = fullfile(matches(1).folder,matches(1).name);
    foldData = load(modelFile,'net','muX','stdX','muy','stdy');
    requiredFields = {'net','muX','stdX','muy','stdy'};
    for iField = 1:numel(requiredFields)
        if ~isfield(foldData,requiredFields{iField})
            error('Required variable "%s" is missing from %s.', ...
                requiredFields{iField},modelFile);
        end
    end
    if ~isSupportedNetwork(foldData.net)
        error('Variable net in %s is not a supported network.',modelFile);
    end
    nets{iFold}  = foldData.net;
    muXs{iFold}  = foldData.muX;
    stdXs{iFold} = foldData.stdX;
    muys{iFold}  = foldData.muy;
    stdys{iFold} = foldData.stdy;
end

RMSE = NaN; R2 = NaN;
fprintf('Loaded MINN five-fold ensemble folder: %s\n',modelFolder);
fprintf('Loaded trained MINN ensemble = %d fold models\n',numel(nets));

%% ============================================================
% MAIN FIGURE
%% ============================================================

fig = figure(...
    'Name','CCFST MINN - Axial Capacity Predictor',...
    'Position',[100 40 1400 850],...
    'Color',[0.94 0.94 0.94],...
    'NumberTitle','off',...
    'MenuBar','none',...
    'Resize','off');

%% ============================================================
% INPUT PANEL
%% ============================================================

pInput = uipanel(fig,...
    'Title','Input Parameters',...
    'FontSize',18,...
    'FontWeight','bold',...
    'BackgroundColor','white',...
    'Position',[0.03 0.08 0.46 0.86]);

names = {'Outer Diameter, D', ...
         'Tube Thickness, t', ...
         'Steel Yield Strength, fy', ...
         'Concrete Strength, fc''', ...
         'Column Length, L'};

units = {'mm','mm','MPa','MPa','mm'};

defaults = [300 6 345 40 900];

fcTypeList = {...
    'fcyl,150x300', ...
    'fcyl,100x200', ...
    'fcyl,250x500', ...
    'fcu,100', ...
    'fcu,150', ...
    'fcu,200', ...
    'fcu,300'};

fcFactorList = [1.00 0.97 1.05 0.80 0.80 0.83 0.90];

editBox = gobjects(1,5);

startY   = 625;
spacingY = 105;

for i = 1:5

    yPos = startY - (i-1)*spacingY;

    % Move Column Length downward
    if i == 5
        yPos = yPos - 25;
    end

    %% ---------- Variable Name ----------
    uicontrol(pInput,...
        'Style','text',...
        'String',names{i},...
        'HorizontalAlignment','left',...
        'FontSize',15,...
        'BackgroundColor','white',...
        'Position',[30 yPos 260 32]);

    %% ---------- Input Box ----------
    editBox(i) = uicontrol(pInput,...
        'Style','edit',...
        'String',num2str(defaults(i)),...
        'BackgroundColor',[0.88 0.95 1.00],...
        'FontSize',17,...
        'FontWeight','bold',...
        'Position',[320 yPos-2 120 40]);

    %% ---------- Unit ----------
    uicontrol(pInput,...
        'Style','text',...
        'String',units{i},...
        'HorizontalAlignment','left',...
        'FontSize',15,...
        'BackgroundColor','white',...
        'Position',[460 yPos 80 32]);

    %% ---------- Concrete Type Below fc' ----------
    if i == 4

        uicontrol(pInput,...
            'Style','text',...
            'String','Concrete Type',...
            'HorizontalAlignment','left',...
            'FontSize',13,...
            'BackgroundColor','white',...
            'Position',[320 yPos-45 160 28]);

        popup_fcType = uicontrol(pInput,...
            'Style','popupmenu',...
            'String',fcTypeList,...
            'FontSize',12,...
            'BackgroundColor',[0.88 0.95 1.00],...
            'Position',[320 yPos-75 220 35]);

    end

end

%% ============================================================
% CONVERTED CONCRETE CYLINDER STRENGTH
%% ============================================================

uicontrol(pInput,...
    'Style','text',...
    'String','Converted Concrete Cylinder Strength',...
    'HorizontalAlignment','left',...
    'FontSize',12,...
    'BackgroundColor','white',...
    'Position',[30 95 420 32]);

txt_fc_conv = uicontrol(pInput,...
    'Style','edit',...
    'String','---',...
    'FontSize',15,...
    'FontWeight','bold',...
    'BackgroundColor',[0.94 0.94 0.94],...
    'Enable','inactive',...
    'HorizontalAlignment','center',...
    'Position',[320 90 120 40]);

uicontrol(pInput,...
    'Style','text',...
    'String','MPa',...
    'HorizontalAlignment','left',...
    'FontSize',15,...
    'BackgroundColor','white',...
    'Position',[460 95 60 30]);

%% ============================================================
% CALCULATED L/D
%% ============================================================

uicontrol(pInput,...
    'Style','text',...
    'String','Calculated L/D',...
    'HorizontalAlignment','left',...
    'FontSize',15,...
    'BackgroundColor','white',...
    'Position',[30 40 260 32]);

txt_LD = uicontrol(pInput,...
    'Style','edit',...
    'String','---',...
    'FontSize',16,...
    'FontWeight','bold',...
    'BackgroundColor',[0.94 0.94 0.94],...
    'Enable','inactive',...
    'Position',[320 35 120 40]);

%% ============================================================
% OUTPUT PANEL
%% ============================================================

pOut = uipanel(fig,...
    'Title','Prediction Results of the Proposed CCFST-MINN Model',...
    'FontSize',17,...
    'FontWeight','bold',...
    'BackgroundColor','white',...
    'Position',[0.52 0.35 0.45 0.59]);

%% ---------- Nu ----------
uicontrol(pOut,...
    'Style','text',...
