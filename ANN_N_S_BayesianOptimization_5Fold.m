function objective = annCVObjective( ...
    T, X, y, cv, K, fixedSeed, numIter, ...
    lambdaData, lambdaReg, lossTol, checkEvery, minIterCheck)

    learnRate = T.LearningRate;
    nNeuron = T.NumNeurons;
    nLayer = T.HiddenLayers;

    foldRMSE = nan(K,1);

    fprintf('\n----------------------------------------------------\n');
    fprintf( ...
        'Bayesian trial | HL=%d | Neurons=%d | LR=%.6e\n', ...
        nLayer,nNeuron,learnRate);

    for fold = 1:K

        idxTr = training(cv,fold);
        idxVa = test(cv,fold);

        Xtr = X(idxTr,:);
        ytr = y(idxTr);

        Xva = X(idxVa,:);
        yva = y(idxVa);

        % Normalization is based ONLY on the training portion of the fold
        muX = mean(Xtr,1);
        stdX = std(Xtr,0,1);
        stdX(stdX==0) = 1;

        muy = mean(ytr);
        stdy = std(ytr);

        if stdy==0
            stdy = 1;
        end

        xTr = dlarray(((Xtr-muX)./stdX)','CB');
        yTr = dlarray(((ytr-muy)./stdy)','CB');
        xVa = dlarray(((Xva-muX)./stdX)','CB');

        % Deterministic seed for comparison between trials
        rng( ...
            fixedSeed + ...
            1000*fold + ...
            round(1e7*learnRate) + ...
            10*nNeuron + ...
            nLayer, ...
            'twister');

        net = buildANN(nLayer,nNeuron);

        trailingAvg = [];
        trailingAvgSq = [];

        lossHistory = nan(numIter,1);

        for it = 1:numIter

            [loss,grad] = dlfeval( ...
                @lossFun, ...
                net, ...
                xTr, ...
                yTr, ...
                lambdaData, ...
                lambdaReg);

            [net,trailingAvg,trailingAvgSq] = adamupdate( ...
                net, ...
                grad, ...
                trailingAvg, ...
                trailingAvgSq, ...
                it, ...
                learnRate);

            lossHistory(it) = gather(extractdata(loss));

            if mod(it,checkEvery)==0 && it>=minIterCheck

                change = abs( ...
                    lossHistory(it) - ...
                    lossHistory(it-checkEvery));

                if change < lossTol
                    break
                end
            end
        end

        predVa = predictReal(net,xVa,muy,stdy);
        metrics = calcMetrics(yva,predVa);

        foldRMSE(fold) = metrics(3);

        fprintf( ...
            ' Fold %d/%d | RMSE=%.3f | R2=%.5f\n', ...
            fold,K,metrics(3),metrics(4));
    end

    objective = mean(foldRMSE);

    fprintf( ...
        ' Mean 5-fold validation RMSE = %.4f kN\n', ...
        objective);
end


function net = buildANN(nLayer,nNeuron)

    layers = featureInputLayer( ...
        5, ...
        'Normalization','none', ...
        'Name','input');

    for L = 1:nLayer

        layers = [
            layers
            fullyConnectedLayer( ...
                nNeuron, ...
                'Name',sprintf('fc%d',L))
            tanhLayer( ...
                'Name',sprintf('tanh%d',L))
        ]; %#ok<AGROW>
    end

    layers = [
        layers
        fullyConnectedLayer(1,'Name','output')
    ];

    net = dlnetwork(layerGraph(layers));
end


function [loss,grad] = lossFun(net,x,y,lambdaData,lambdaReg)

    yp = forward(net,x,'Outputs','output');

    dataLoss = mean((yp-y).^2,'all');

    reg = dlarray(0);

    vals = net.Learnables.Value;

    for q = 1:numel(vals)
        reg = reg + sum(vals{q}.^2,'all');
    end

    loss = lambdaData.*dataLoss + lambdaReg.*reg;

    grad = dlgradient(loss,net.Learnables);
end


function pred = predictReal(net,x,muy,stdy)

    p = forward(net,x,'Outputs','output');

    pred = gather(extractdata(p))'.*stdy + muy;
end


function m = calcMetrics(obs,pred)

    err = pred-obs;

    mae = mean(abs(err));
    mse = mean(err.^2);
    rmse = sqrt(mse);

    den = sum((obs-mean(obs)).^2);

    if den>0
        r2 = 1-sum(err.^2)/den;
    else
        r2 = NaN;
    end

    ratio = pred./obs;

    valid = isfinite(ratio);

    a20 = mean( ...
        ratio(valid)>=0.8 & ...
        ratio(valid)<=1.2)*100;

    meanRatio = mean(ratio(valid));
    sdRatio = std(ratio(valid));

    m = [
        mae, ...
        mse, ...
        rmse, ...
        r2, ...
        a20, ...
        meanRatio, ...
        sdRatio
    ];
end
