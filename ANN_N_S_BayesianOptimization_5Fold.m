%% ANN BAYESIAN OPTIMIZATION WITH 5-FOLD CROSS-VALIDATION
% Optimize ONLY ANN hyperparameters:
%   1) Learning rate
%   2) Number of neurons per hidden layer
%   3) Number of hidden layers
%
% Selection criterion: minimum mean 5-fold validation RMSE.
% Independent testing data are NOT used during Bayesian optimization.

clear; clc; close all;
tTotal = tic;

%% EXPORT COMMAND WINDOW TO TEXT FILE
commandWindowFile = 'ANN_N_S_BayesianOptimization_5Fold_CommandWindow.txt';
if exist(commandWindowFile,'file')
    delete(commandWindowFile);
end
diary(commandWindowFile);
cleanupDiary = onCleanup(@() diary('off'));
fprintf('Command Window log started: %s\n', datestr(now,'yyyy-mm-dd HH:MM:SS'));

%% 1) SETTINGS
trainFile = 'N_S_Training_DATASET_75.xlsx';
testFile  = 'N_S_Testing_DATASET_25.xlsx';

K = 5;
fixedSeed = 1;

% ===== Bayesian Optimization =====
maxObjectiveEvaluations = 60;

% Search ranges
learningRateRange = [1e-5 5e-4];
numNeuronsRange   = [8 128];
hiddenLayersRange = [2 5];

% ===== Fixed ANN Settings =====
numIter = 100000;

lambda_data_total = 0.005;
lambda_reg = 1e-7;

lossTol = 1e-5;
checkEvery = 5000;
minIterCheck = 10000;

outDir = 'Results_ANN_N_S_BayesianOptimization_5Fold';
if ~exist(outDir,'dir')
    mkdir(outDir);
end

excelFile = fullfile(outDir,'ANN_N_S_BayesianOptimization_5Fold_Results.xlsx');
matFile   = fullfile(outDir,'ANN_N_S_BayesianOptimization_5Fold_Results.mat');

rng(fixedSeed,'twister');

try
    gpuDevice([]);
catch
end

%% 2) LOAD DATA
Tr = readtable(trainFile,'VariableNamingRule','preserve');
Te = readtable(testFile ,'VariableNamingRule','preserve');

Tr.Properties.VariableNames = matlab.lang.makeValidName( ...
    strtrim(Tr.Properties.VariableNames));

Te.Properties.VariableNames = matlab.lang.makeValidName( ...
    strtrim(Te.Properties.VariableNames));

X = [Tr.D Tr.t Tr.fy Tr.fc Tr.L_D];
y = Tr.N;

Xtest = [Te.D Te.t Te.fy Te.fc Te.L_D];
ytest = Te.N;

n = size(X,1);
nTest = size(Xtest,1);

% Fixed folds for fair comparison among Bayesian trials
rng(fixedSeed,'twister');
cv = cvpartition(n,'KFold',K);

fprintf('\n====================================================\n');
fprintf('ANN BAYESIAN OPTIMIZATION + %d-FOLD CV\n',K);
fprintf('Maximum Bayesian evaluations = %d\n',maxObjectiveEvaluations);
fprintf('Testing set is excluded from optimization.\n');
fprintf('====================================================\n');

%% 3) BAYESIAN SEARCH SPACE
optimVars = [
    optimizableVariable('LearningRate',learningRateRange, ...
        'Transform','log')

    optimizableVariable('NumNeurons',numNeuronsRange, ...
        'Type','integer')

    optimizableVariable('HiddenLayers',hiddenLayersRange, ...
        'Type','integer')
];

%% 4) BAYESIAN OPTIMIZATION
objectiveFcn = @(T) annCVObjective( ...
    T, X, y, cv, K, fixedSeed, numIter, ...
    lambda_data_total, lambda_reg, ...
    lossTol, checkEvery, minIterCheck);

bayesResults = bayesopt( ...
    objectiveFcn, ...
    optimVars, ...
    'MaxObjectiveEvaluations',maxObjectiveEvaluations, ...
    'IsObjectiveDeterministic',true, ...
    'AcquisitionFunctionName','expected-improvement-plus', ...
    'UseParallel',false, ...
    'Verbose',1, ...
    'PlotFcn',[]);

%% 5) BEST HYPERPARAMETERS
% Use the best OBSERVED objective point. This is compatible with MATLAB
% versions that do not provide bestPointByMinObjective().
bestPoint = bayesResults.XAtMinObjective;

bestLearningRate = bestPoint.LearningRate;
bestNumNeurons   = bestPoint.NumNeurons;
bestHiddenLayers = bestPoint.HiddenLayers;

bestCV_RMSE = bayesResults.MinObjective;

fprintf('\n================ BEST BAYESIAN RESULT ================\n');
fprintf('Hidden layers = %d\n',bestHiddenLayers);
fprintf('Neurons       = %d\n',bestNumNeurons);
fprintf('Learning rate = %.6e\n',bestLearningRate);
fprintf('Best mean validation RMSE = %.4f kN\n',bestCV_RMSE);

%% 6) RETRAIN BEST HYPERPARAMETERS ON EACH OF THE 5 FOLDS
bestFoldModels = cell(K,1);
bestFoldMuX = cell(K,1);
bestFoldStdX = cell(K,1);
bestFoldMuy = nan(K,1);
bestFoldStdy = nan(K,1);

bestFoldMetrics = nan(K,7);
bestFoldStopIteration = nan(K,1);
bestFoldTrainingTime = nan(K,1);

for fold = 1:K

    idxTr = training(cv,fold);
    idxVa = test(cv,fold);

    Xtr = X(idxTr,:);
    ytr = y(idxTr);

    Xva = X(idxVa,:);
    yva = y(idxVa);

    muX = mean(Xtr,1);
    stdX = std(Xtr,0,1);
    stdX(stdX==0) = 1;

    muy = mean(ytr);
    stdy = std(ytr);
    if stdy==0
        stdy = 1;
    end

    xTr = dlarray(((Xtr-muX)./stdX)','CB');
    yTr = dlarray(((ytr-muy)./stdy)','CB');
    xVa = dlarray(((Xva-muX)./stdX)','CB');

    rng(fixedSeed + 10000 + fold,'twister');

    net = buildANN(bestHiddenLayers,bestNumNeurons);

    trailingAvg = [];
    trailingAvgSq = [];
    lossHistory = nan(numIter,1);

    stopIteration = numIter;

    tFold = tic;

    for it = 1:numIter

        [loss,grad] = dlfeval( ...
            @lossFun, ...
            net, ...
            xTr, ...
            yTr, ...
            lambda_data_total, ...
            lambda_reg);

        [net,trailingAvg,trailingAvgSq] = adamupdate( ...
            net, ...
            grad, ...
            trailingAvg, ...
            trailingAvgSq, ...
            it, ...
            bestLearningRate);

        lossHistory(it) = gather(extractdata(loss));

        if mod(it,checkEvery)==0 && it>=minIterCheck

            change = abs( ...
                lossHistory(it) - ...
                lossHistory(it-checkEvery));

            if change < lossTol
                stopIteration = it;
                break
            end
        end
    end

    bestFoldTrainingTime(fold) = toc(tFold);
    bestFoldStopIteration(fold) = stopIteration;

    predVa = predictReal(net,xVa,muy,stdy);

    bestFoldMetrics(fold,:) = calcMetrics(yva,predVa);

    bestFoldModels{fold} = net;
    bestFoldMuX{fold} = muX;
    bestFoldStdX{fold} = stdX;
    bestFoldMuy(fold) = muy;
    bestFoldStdy(fold) = stdy;

    fprintf( ...
        'Fold %d/%d | Iter=%d | Val RMSE=%.3f | R2=%.5f\n', ...
        fold, ...
        K, ...
        stopIteration, ...
        bestFoldMetrics(fold,3), ...
        bestFoldMetrics(fold,4));
end

%% 7) INDEPENDENT TESTING
testPredByFold = nan(nTest,K);

for fold = 1:K

    xTest = dlarray( ...
        ((Xtest-bestFoldMuX{fold})./bestFoldStdX{fold})', ...
        'CB');

    testPredByFold(:,fold) = predictReal( ...
        bestFoldModels{fold}, ...
        xTest, ...
        bestFoldMuy(fold), ...
        bestFoldStdy(fold));
end

% Ensemble prediction of five independently trained fold models
testPred = mean(testPredByFold,2);

testMetrics = calcMetrics(ytest,testPred);

fprintf('\n================ INDEPENDENT TESTING ================\n');
fprintf('MAE  = %.3f kN\n',testMetrics(1));
fprintf('MSE  = %.3f kN^2\n',testMetrics(2));
fprintf('RMSE = %.3f kN\n',testMetrics(3));
fprintf('R2   = %.5f\n',testMetrics(4));
